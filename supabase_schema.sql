-- ------------------------------------------------------------------------------
-- 3. TABEL PROFILES UNTUK VERIFIKASI ROLE ADMIN
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    role TEXT DEFAULT 'admin' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Aktifkan RLS pada tabel profiles
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- Policy SELECT: User yang login hanya boleh membaca profil miliknya sendiri
DROP POLICY IF EXISTS "Allow authenticated read own profile" ON public.profiles;
DROP POLICY IF EXISTS "Allow authenticated read profiles" ON public.profiles;
CREATE POLICY "Allow authenticated read own profile"
ON public.profiles
FOR SELECT
TO authenticated
USING (auth.uid() = id);

-- ------------------------------------------------------------------------------
-- 4. POLICIES CRUD TABEL PROYEK (HANYA UNTUK USER BER-ROLE 'admin' DI TABEL PROFILES)
-- ------------------------------------------------------------------------------

-- Policy 1: INSERT HANYA untuk user dengan role 'admin'
DROP POLICY IF EXISTS "Allow authenticated insert" ON public.proyek;
DROP POLICY IF EXISTS "Allow admin insert" ON public.proyek;
CREATE POLICY "Allow admin insert"
ON public.proyek
FOR INSERT
TO authenticated
WITH CHECK (
  EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid() AND profiles.role = 'admin'
  )
);

-- Policy 2: UPDATE HANYA untuk user dengan role 'admin'
DROP POLICY IF EXISTS "Allow authenticated update" ON public.proyek;
DROP POLICY IF EXISTS "Allow admin update" ON public.proyek;

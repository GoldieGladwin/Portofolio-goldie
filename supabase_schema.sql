-- ------------------------------------------------------------------------------
-- 6. MEMBUAT 1 AKUN ADMIN OTOMATIS (AUTH.USERS + AUTH.IDENTITIES + PROFILES)
-- ------------------------------------------------------------------------------
-- Kredensial Akun Admin:
-- Email    : admin@gmail.com
-- Password : AdminPassword123!
-- ------------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

DO $$
DECLARE
  v_user_id UUID := gen_random_uuid();
  v_email TEXT := 'admin@gmail.com';
  v_password TEXT := 'AdminPassword123!';
BEGIN
  -- Cek jika akun belum ada di auth.users
  IF NOT EXISTS (SELECT 1 FROM auth.users WHERE email = v_email) THEN
    -- 1. Insert ke auth.users
    INSERT INTO auth.users (
      id,
      instance_id,
      aud,
      role,
      email,
      encrypted_password,
      email_confirmed_at,
      raw_app_meta_data,
      raw_user_meta_data,
      created_at,
      updated_at
    ) VALUES (
      v_user_id,
      '00000000-0000-0000-0000-000000000000',
      'authenticated',
      'authenticated',
      v_email,
      crypt(v_password, gen_salt('bf')),
      NOW(),
      '{"provider":"email","providers":["email"]}'::jsonb,
      '{}'::jsonb,
      NOW(),
      NOW()
    );

    -- 2. Hubungkan identitas email ke auth.identities (wajib untuk GoTrue Supabase Auth)
    INSERT INTO auth.identities (
      id,
      user_id,
      provider_id,
      identity_data,
      provider,
      last_sign_in_at,
      created_at,
      updated_at
    ) VALUES (
      v_user_id,
      v_user_id,
      v_user_id,
      jsonb_build_object('sub', v_user_id, 'email', v_email),
      'email',
      NOW(),
      NOW(),
      NOW()
    );

    -- 3. Masukkan ke public.profiles dengan role 'admin'
    INSERT INTO public.profiles (id, email, role)
    VALUES (v_user_id, v_email, 'admin')
    ON CONFLICT (id) DO UPDATE SET role = 'admin';

  ELSE
    -- Jika user dengan email tersebut sudah pernah dibuat di auth.users:
    -- Ambil ID user lama dan pastikan terdaftar di tabel public.profiles sebagai admin
    SELECT id INTO v_user_id FROM auth.users WHERE email = v_email;
    
    -- Update password akun yang sudah ada ke AdminPassword123!
    UPDATE auth.users
    SET encrypted_password = crypt(v_password, gen_salt('bf')),
        email_confirmed_at = COALESCE(email_confirmed_at, NOW())
    WHERE id = v_user_id;

    INSERT INTO public.profiles (id, email, role)
    VALUES (v_user_id, v_email, 'admin')
    ON CONFLICT (id) DO UPDATE SET role = 'admin';
  END IF;
END $$;
